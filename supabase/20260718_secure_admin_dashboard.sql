  balance_after INTEGER NOT NULL CHECK (balance_after >= 0), entry_type TEXT NOT NULL,
  reason TEXT NOT NULL, idempotency_key TEXT NOT NULL UNIQUE, actor_user_id UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

