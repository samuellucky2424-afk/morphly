ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS account_status TEXT NOT NULL DEFAULT 'active',
  ADD COLUMN IF NOT EXISTS suspended_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS suspended_by UUID,
  ADD COLUMN IF NOT EXISTS suspension_reason TEXT;

DO $$ BEGIN
  ALTER TABLE public.users ADD CONSTRAINT users_account_status_check
    CHECK (account_status IN ('active', 'suspended'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

ALTER TABLE public.credit_packages
  ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'active',
  ADD COLUMN IF NOT EXISTS is_recommended BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE public.credit_packages SET status = CASE WHEN is_active THEN 'active' ELSE 'paused' END
WHERE status IS NULL OR status NOT IN ('active', 'draft', 'paused');
DO $$ BEGIN
  ALTER TABLE public.credit_packages ADD CONSTRAINT credit_packages_status_check
    CHECK (status IN ('active', 'draft', 'paused'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE UNIQUE INDEX IF NOT EXISTS one_recommended_credit_package
  ON public.credit_packages (is_recommended) WHERE is_recommended = TRUE;

ALTER TABLE public.transactions
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS payment_gateway TEXT,
  ADD COLUMN IF NOT EXISTS gateway_transaction_id TEXT,
  ADD COLUMN IF NOT EXISTS gateway_fee_ngn NUMERIC(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS refund_status TEXT NOT NULL DEFAULT 'none',
  ADD COLUMN IF NOT EXISTS package_id UUID REFERENCES public.credit_packages(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS package_name_snapshot TEXT,
  ADD COLUMN IF NOT EXISTS package_price_snapshot_ngn NUMERIC(12,2),
  ADD COLUMN IF NOT EXISTS package_credits_snapshot INTEGER,
  ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ;
CREATE UNIQUE INDEX IF NOT EXISTS transactions_reference_unique ON public.transactions(reference) WHERE reference IS NOT NULL;
